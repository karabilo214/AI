"""Заготовки областей мозга (параметры на глаз, без эволюции).

    быстрая память  учится в 10 раз быстрее и сама забывает: сила входящих
                    связей возвращается к исходной на 0.3% за шаг (~300 шагов)
    память          заряд почти не стекает (0.99 за шаг вместо обычного),
                    входящие связи жёсткие: держит то, что было показано
    действия        обычные нейроны (обучение по награде, соревнование)
    контекст        заряд стекает медленно (0.97): держит условия дольше
    зрение          вход: картинка = несколько нейронов сразу (обычные нейроны)
    слух            вход: слово = звуки один за другим (обычные нейроны)
    память слуха    нейроны порядка звуков (Hearing.py): связи жёсткие,
                    их активность считается восприятием

Использование:
    from human_brain.core.Regions import add_standard_regions
    add_standard_regions(brain)
    brain.add_neuron("M1", region="память")
"""

STANDARD = {
    "быстрая память": dict(learn=10.0, relax=0.003),
    "память": dict(decay=0.99, learn=0.0),
    "действия": dict(),
    "контекст": dict(decay=0.97),
    "зрение": dict(),
    "слух": dict(),
    "память слуха": dict(learn=0.0, perceptual=True),
}


def add_standard_regions(brain):
    for name, props in STANDARD.items():
        brain.add_region(name, **props)

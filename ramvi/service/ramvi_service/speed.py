"""Примерная скорость генерации по плану движка (4.4): не замер, а оценка.

Генерация одного токена упирается в чтение весов: каждый слой читается целиком
(у MoE — только выбранные эксперты) оттуда, где он лежит по плану. Время на токен:

    t = байты_в_VRAM / VRAM + байты_на_CPU / RAM + байты_по_шине / PCIe + нехватка_RAM / диск
        + слои × плата_за_слой

Плата за слой — запуск ядер и синхронизации, от размера весов не зависит; у маленьких
моделей она главная (без неё 0.6B «получила» бы 600+ ток/с).

Слои «hyb» при одиночном шаге считает процессор — они идут как CPU. Процессор и шина
могут работать одновременно, а могут ждать друг друга, поэтому результат — диапазон:
нижняя граница — всё по очереди (и ещё −15 % на накладные расходы), верхняя — CPU и
шина параллельно. Угадыватель (draft) не учитывается: с ним на 14B было ×1,5.

Скорости подобраны по замерам на ноутбуке RTX 5060 8 ГБ, Ryzen 7 260 (8 ядер),
16 ГБ DDR5 в один канал (подробно — COMPATIBILITY.md). Проверка формулы на них:
8B Q4 целиком в VRAM — замер 55–58 ток/с (из него — плата за слой); 14B Q4 21 слой в VRAM — 5,6–6,1;
8B F16 — 2,35; 30B MoE 14 слоёв в VRAM — 8–9,7. На другом железе пропускную
способность памяти мы не знаем; число ядер учитывается как предел чтения RAM.
Точное число на этом ПК даст контрольный прогон (4.7).
"""

from dataclasses import dataclass

GB = 1e9
VRAM_BPS = 340 * GB  # gemv в CUDA-графе 320–360 ГБ/с
# 8B Q4 целиком в VRAM: 1/57 ток/с = 17,5 мс, из них чтение 4,87 ГБ / 340 ГБ/с = 14,3 мс;
# остаток на 36 слоёв — 89 мкс. Проверка: 0.6B (28 слоёв) — 3,8 мс, замер 3,4 мс.
LAYER_S = (1 / 57 - 4.87 * GB / VRAM_BPS) / 36
RAM_BPS = 25 * GB  # чтение RAM 25–26 ГБ/с, слой C++ 27 ГБ/с (один канал DDR5-5600)
RAM_BPS_PER_CORE = 4 * GB  # мало ядер — RAM не прочитать на полной скорости
PCIE_BPS = 14.5 * GB  # шина из закреплённой памяти
DISK_BPS = 2.3 * GB  # SSD: веса, не поместившиеся в RAM, дочитываются каждый токен
# Слой MoE на CPU: активные веса ~34 МБ за 2,85 мс (замер) против 1,38 мс при 25 ГБ/с.
MOE_CPU_EFFICIENCY = 1.38 / 2.85
OVERHEAD = 0.85  # запуск ядер, синхронизации, Python — к нижней границе


@dataclass(frozen=True)
class Traffic:
    """Сколько байт весов читается на один токен из каждого места."""

    vram: int = 0
    cpu: int = 0
    bus: int = 0
    disk: int = 0
    moe: bool = False
    layers: int = 0


def tokens_per_second(traffic: Traffic, cores: int | None) -> tuple[float, float] | None:
    """(нижняя, верхняя) граница ток/с; None — нечего оценивать."""
    ram = RAM_BPS if cores is None else min(RAM_BPS, cores * RAM_BPS_PER_CORE)
    if traffic.moe:
        ram *= MOE_CPU_EFFICIENCY
    gpu = traffic.vram / VRAM_BPS
    cpu = traffic.cpu / ram
    bus = traffic.bus / PCIE_BPS
    disk = traffic.disk / DISK_BPS + traffic.layers * LAYER_S
    serial = gpu + cpu + bus + disk
    if serial <= 0:
        return None
    parallel = gpu + max(cpu, bus) + disk
    return OVERHEAD / serial, 1 / parallel


def rounded(value: float) -> float:
    """Две значащие цифры: 57.3 → 57, 5.83 → 5.8, 0.312 → 0.31."""
    if value <= 0:
        return 0.0
    return float(f"{value:.2g}")
